'use strict';

module.exports = function renderFooter(block, ctx) {

    const geometry = block.geometry;
    const data = block.data ?? {};
    const tokens = ctx.tokens ?? {};

    const typography =
        tokens.typography?.footer ?? {
            font: 'Helvetica',
            size: 9,
            lineHeight: 14,
            color: '#6B7280'
        };

    const spacing = {
        bottom: tokens.spacing?.footerBottom ?? 16
    };

    const lineColor =
        tokens.colors?.border ??
        '#E5E7EB';

    const left =
        data.left ??
        'Generated by LOREVI';

    const center =
        data.center ??
        '';

    const right =
        data.right ??
        `Page ${data.page ?? 1}`;

    ctx.line({

        x1: geometry.x,
        y1: geometry.y,

        x2: geometry.x + geometry.width,
        y2: geometry.y,

        color: lineColor,
        width: 1

    });

    const y =
        geometry.y +
        geometry.height -
        spacing.bottom;

    ctx.text(left, {

        x: geometry.x,
        y,

        width: geometry.width * 0.4,
        height: typography.lineHeight,

        font: typography.font,
        size: typography.size,
        color: typography.color,
        lineHeight: typography.lineHeight,

        align: 'left',
        valign: 'top',
        wrap: false

    });

    if (center) {

        ctx.text(center, {

            x: geometry.x + geometry.width * 0.3,
            y,

            width: geometry.width * 0.4,
            height: typography.lineHeight,

            font: typography.font,
            size: typography.size,
            color: typography.color,
            lineHeight: typography.lineHeight,

            align: 'center',
            valign: 'top',
            wrap: false

        });

    }

    ctx.text(right, {

        x: geometry.x + geometry.width * 0.7,
        y,

        width: geometry.width * 0.3,
        height: typography.lineHeight,

        font: typography.font,
        size: typography.size,
        color: typography.color,
        lineHeight: typography.lineHeight,

        align: 'right',
        valign: 'top',
        wrap: false

    });

};
