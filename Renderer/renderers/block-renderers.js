    function renderArchitecture(block,ctx){
        const g=block.geometry; card(ctx,g);
        const sp=spacing(ctx); let y=sectionHeader(ctx,g,title(ctx,'architecture'),'purplePrimary');
        const sections=architectureFrom(block,ctx.report||{});
        const cols=Math.min(4,Math.max(1,sections.length)), gap=sp.cardGap;
        const innerX=g.x+sp.padX, innerW=g.width-sp.padX*2, colW=(innerW-gap*(cols-1))/cols;
        const accents=['purplePrimary','greenSuccess','orangeRisk','purplePrimary'];
        const iconNames=['file-text','brain-circuit','database','settings'];
        sections.forEach((sec,i)=>{
            const x=innerX+i*(colW+gap), bottom=g.y+g.height-sp.padY;
            ctx.rect({x,y,width:colW,height:bottom-y,fill:'cardBg',stroke:'borderDefault',borderWidth:.5,radius:3});
            const continuationScale=Math.max(1,Math.min(1.55,Number(block?.layout?.contentScale)||1));
            const secNoBase=style(ctx,'architectureSectionNo',{font:'bold',size:6.5,lineHeight:7.5,color:'textPrimary'});
            const secTitleBase=style(ctx,'architectureSectionTitle',{font:'bold',size:6.3,lineHeight:7.7,color:'textPrimary'});
            const secNo={...secNoBase,size:secNoBase.size*continuationScale,lineHeight:secNoBase.lineHeight*continuationScale};
            const secTitle={...secTitleBase,size:secTitleBase.size*continuationScale,lineHeight:secTitleBase.lineHeight*continuationScale};
            ctx.text(String(i+1),{x:x+6,y:y+6,size:secNo.size,font:secNo.font,color:accents[i]});
            let sy=y+6+textLines(ctx,clean(sec?.title||sec?.name),x+17,y+6,colW-22,secTitle)+3*continuationScale;
            const items=Array.isArray(sec?.items)?sec.items:[];
            // Fit all semantic content inside the immutable architecture card.
            // We only reduce visual typography within the approved dense floor; nothing is removed.
            // Page-aware typography: continuation pages often have substantially
            // more free vertical space. Use it to improve readability instead of
            // carrying the dense first-page architecture typography forward.
            // The scale is still content-fit constrained below, so no clipping is introduced.
            const maxScale=continuationScale;
            let scale=maxScale;
            const available=bottom-sy-2;
            function estimate(sc){
                let h=0;
                const itBase=style(ctx,'architectureItemTitle',{font:'semibold',size:5.1,lineHeight:6.2,color:'textPrimary'});
                const dsBase=style(ctx,'architectureDescription',{font:'regular',size:4.6,lineHeight:5.6,color:'textSecondary'});
                const it={...itBase,size:itBase.size*sc,lineHeight:itBase.lineHeight*sc};
                const ds={...dsBase,size:dsBase.size*sc,lineHeight:dsBase.lineHeight*sc};
                items.forEach(item=>{
                    h+=wrap(ctx,clean(item?.title||item?.name||item?.label),colW-19,it).length*it.lineHeight;
                    const d=clean(item?.description||item?.text||'');
                    if(d)h+=wrap(ctx,d,colW-19,ds).length*ds.lineHeight;
                    h+=1.4;
                });
                return h;
            }
            while(scale>.78 && estimate(scale)>available)scale-=.04;
            const itemBase=style(ctx,'architectureItemTitle',{font:'semibold',size:5.1,lineHeight:6.2,color:'textPrimary'});
            const descBase=style(ctx,'architectureDescription',{font:'regular',size:4.6,lineHeight:5.6,color:'textSecondary'});
            const itemTitle={...itemBase,size:itemBase.size*scale,lineHeight:itemBase.lineHeight*scale};
            const desc={...descBase,size:descBase.size*scale,lineHeight:descBase.lineHeight*scale};

            // Compute the actual rendered semantic height, then convert only true surplus
            // into inter-item breathing room. Works for any language/content length.
            const naturalItemHeights=items.map(item=>{
                const t=clean(item?.title||item?.name||item?.label);
                const d=clean(item?.description||item?.text||'');
                let h=wrap(ctx,t,colW-18,itemTitle).length*itemTitle.lineHeight;
                if(d)h+=wrap(ctx,d,colW-18,desc).length*desc.lineHeight;
                return h;
            });
            const naturalItemsH=naturalItemHeights.reduce((sum,h)=>sum+h,0);
            const semanticGaps=Math.max(0,items.length-1);
            const spareH=Math.max(0,bottom-sy-naturalItemsH);
            const adaptiveSemanticGap=semanticGaps
                ? Math.min(spareH/semanticGaps,itemTitle.lineHeight*1.15)
                : 0;

            items.forEach((item,j)=>{
                icon(ctx,iconNames[(i+j)%iconNames.length],x+5,sy,6.5*scale,accents[i]);
                const t=clean(item?.title||item?.name||item?.label), d=clean(item?.description||item?.text||'');
                sy+=textLines(ctx,t,x+13,sy,colW-18,itemTitle);
                if(d)sy+=textLines(ctx,d,x+13,sy,colW-18,desc);
                if(j<items.length-1)sy+=adaptiveSemanticGap;
            });
            const archData=blockData(block)||{};
            const explicitMode=clean(archData?.mode||archData?.type||archData?.layout||archData?.kind).toLowerCase();
            const sectionMode=clean(sec?.mode||sec?.type||sec?.layout||sec?.kind).toLowerCase();
            const rootFlow=
                ['flow','process','pipeline','sequence','workflow'].includes(explicitMode) ||
                archData?.isFlow===true || archData?.is_flow===true ||
                archData?.isProcess===true || archData?.is_process===true ||
                (Array.isArray(archData?.edges) && archData.edges.length>0) ||
                (Array.isArray(archData?.connections) && archData.connections.length>0);
            const sectionFlow=
                ['flow','process','pipeline','sequence','workflow'].includes(sectionMode) ||
                sec?.isFlow===true || sec?.is_flow===true ||
                sec?.isProcess===true || sec?.is_process===true ||
                (Array.isArray(sec?.edges) && sec.edges.length>0) ||
                (Array.isArray(sec?.connections) && sec.connections.length>0);
            const hasExplicitFlow=rootFlow||sectionFlow;
            if(hasExplicitFlow && i<sections.length-1)ctx.text('›',{x:x+colW+gap/2-1.5,y:y+8,size:6,font:'bold',color:'textMuted'});
        });
    }

