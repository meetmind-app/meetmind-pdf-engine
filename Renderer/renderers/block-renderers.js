    function formatMeetingDate(value,ctx){
        const raw=clean(value);
        if(!raw)return '';
        const d=new Date(raw);
        if(Number.isNaN(d.getTime()))return raw;
        try{
            const locale={
                en:'en-US',ru:'ru-RU',es:'es-ES',pt:'pt-BR',tr:'tr-TR',
                id:'id-ID',hi:'hi-IN',ar:'ar-SA',uz:'uz-UZ',fa:'fa-IR'
            }[lang(ctx)]||'en-US';
            return new Intl.DateTimeFormat(locale,{day:'numeric',month:'long',year:'numeric'}).format(d);
        }catch{return raw;}
    }
    function formatDuration(seconds,ctx){
        const n=Number(seconds);
        if(!Number.isFinite(n)||n<=0)return '';
        const total=Math.round(n/60);
        const h=Math.floor(total/60), m=total%60;
        return h?`${h}:${String(m).padStart(2,'0')}`:`${m} ${title(ctx,'minuteShort')}`;
    }
    function formatClock(value,ctx){
        const raw=clean(value);
        if(!raw)return '';
        const d=new Date(raw);
        if(!Number.isNaN(d.getTime())){
            try{
                const locale={
                    en:'en-US',ru:'ru-RU',es:'es-ES',pt:'pt-BR',tr:'tr-TR',
                    id:'id-ID',hi:'hi-IN',ar:'ar-SA',uz:'uz-UZ',fa:'fa-IR'
                }[lang(ctx)]||'en-US';
                return new Intl.DateTimeFormat(locale,{hour:'2-digit',minute:'2-digit',hour12:false}).format(d);
            }catch{}
        }
        const m=raw.match(/(?:^|\s)([0-2]?\d:[0-5]\d)(?:\s|$)/);
        return m?m[1]:'';
    }
